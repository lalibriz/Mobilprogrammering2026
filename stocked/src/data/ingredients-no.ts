const EN_TO_NO: Record<string, string> = {};
for (const [no, en] of Object.entries(NO_TO_EN)) EN_TO_NO[en] ??= no;

export function toEnglish(norwegian: string): string | undefined {
  return NO_TO_EN[norwegian.trim().toLowerCase()];
}

export function toNorwegian(english: string): string {
  const no = EN_TO_NO[english.trim().toLowerCase()];
  return no ? no.charAt(0).toUpperCase() + no.slice(1) : english;
}
